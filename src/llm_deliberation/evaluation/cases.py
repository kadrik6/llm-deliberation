"""Version-controlled evaluation case format (Part B, Section 12) --
plain JSON files under eval_cases/, one case per file, meant to be reviewed
and committed like code.

Public/reviewer separation (see docs/verification-matrix.md's pre-publication
audit): `EvalCase` carries only fields that are safe to publish before a
human blind review ever happens -- the model-visible question/context plus
plain identifying metadata. It never carries `important_constraints` or
`review_notes`, even when the underlying JSON file happens to still contain
those keys (e.g. an older, single-file-style case like
eval_cases/example-nonprofit-crm.json, whose reviewer_notes was audited as
non-sensitive and left as-is -- see below).

Reviewer-only evaluation metadata (`ReviewerMetadata`: `important_constraints`,
`review_notes`) is loaded separately, via `load_reviewer_metadata`, from
either a private, gitignored sidecar file under `eval_private/` (the pattern
for a case whose reviewer key must not be published before scoring -- see
Case 3) or, for backward compatibility, from the same fields embedded
directly in the case's own public file (Pilot Case 1's style). This is
optional by design: a fresh clone of this repository with no `eval_private/`
directory at all can still load every public case, run every variant, and
export blind reviews -- nothing in the ordinary run path ever needs reviewer
metadata to exist.

`important_constraints` must always be manually authored by a human before
a case is used in a *scored* experiment -- never generated by an LLM as part
of the experiment itself (that would let the same kind of model silently
grade its own homework). This module only loads/validates the format; it
never invents or edits constraints.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path

DEFAULT_CASES_DIR = Path("eval_cases")
DEFAULT_PRIVATE_DIR = Path("eval_private")


@dataclass(slots=True)
class EvalCase:
    """Public, model-visible case definition -- safe to publish before any
    human blind review. Contains nothing a reviewer should not see before
    scoring; see ReviewerMetadata for that."""

    case_id: str
    title: str
    question: str
    context: str | None
    output_language: str
    expected_deliverable: str


def load_case(path: str | Path) -> EvalCase:
    data = json.loads(Path(path).read_text())
    required = {"case_id", "title", "question", "output_language", "expected_deliverable"}
    missing = required - data.keys()
    if missing:
        raise ValueError(f"Case file {path} is missing required fields: {sorted(missing)}")
    return EvalCase(
        case_id=data["case_id"],
        title=data["title"],
        question=data["question"],
        context=data.get("context"),
        output_language=data["output_language"],
        expected_deliverable=data["expected_deliverable"],
    )
    # Deliberately ignores `important_constraints`/`review_notes` even when
    # present in this same file -- see load_reviewer_metadata, never this
    # function, for those. A public case file predating this split (Pilot
    # Case 1) still loads correctly; its extra keys are simply unread here.


def load_cases(directory: str | Path = DEFAULT_CASES_DIR) -> list[EvalCase]:
    directory = Path(directory)
    if not directory.is_dir():
        return []
    return [
        load_case(path)
        for path in sorted(directory.glob("*.json"))
    ]


MODEL_INPUT_FINGERPRINT_FIELDS: tuple[str, ...] = ("case_id", "question", "context", "output_language")


def model_input_fingerprint(case: EvalCase) -> str:
    """Deterministic SHA-256 over exactly the model-visible fields of a
    case -- case_id, question, context, output_language, in that order, as
    a compact canonical JSON object (UTF-8, no extra whitespace, fixed key
    order). Deliberately excludes `title` and `expected_deliverable` (never
    read by evaluation.variants.run_variant) and cannot include reviewer
    metadata at all, since EvalCase never carries those fields.

    Exists so a case's model-visible identity can be verified independent
    of which git commit introduced it -- see Case 3's history, where the
    original authoring commit is intentionally not published because it
    also contained reviewer-only metadata (see
    docs/verification-matrix.md).
    """
    canonical = json.dumps(
        {name: getattr(case, name) for name in MODEL_INPUT_FINGERPRINT_FIELDS},
        ensure_ascii=False,
        separators=(",", ":"),
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


@dataclass(slots=True)
class ReviewerMetadata:
    """Reviewer-only evaluation metadata -- must never reach a model prompt
    or a blind-review export (see test_evaluation_case_separation.py).
    Loaded separately from EvalCase, and only ever needed for a human
    scoring workflow, never for running a variant."""

    important_constraints: list[str] = field(default_factory=list)
    review_notes: str | None = None

    def __post_init__(self) -> None:
        if not self.important_constraints:
            raise ValueError(
                "ReviewerMetadata has no important_constraints -- these must be "
                "manually authored before a case can be scored (see this module's docstring)."
            )


def load_reviewer_metadata(
    case_id: str,
    *,
    cases_dir: str | Path = DEFAULT_CASES_DIR,
    private_dir: str | Path = DEFAULT_PRIVATE_DIR,
) -> ReviewerMetadata | None:
    """Load a case's reviewer-only metadata, if any exists, checking two
    sources in order:

    1. a private sidecar file at `<private_dir>/<case_id>.review.json` --
       the pattern for a case whose reviewer key must not be published
       before scoring (e.g. Case 3). This directory is gitignored; it will
       not exist on a fresh public clone.
    2. `important_constraints`/`review_notes` keys embedded directly in the
       case's own public file under `cases_dir` -- the older, single-file
       style still used by a case with no sensitive reviewer content (e.g.
       eval_cases/example-nonprofit-crm.json, already unblinded).

    Returns None if neither source has this case's reviewer metadata --
    e.g. exactly what happens on a fresh public clone with no
    eval_private/ directory, for a case that also has no embedded reviewer
    fields. Never raises for a missing source; only
    ReviewerMetadata.__post_init__ (empty important_constraints) can still
    raise, exactly as before this split.
    """
    private_path = Path(private_dir) / f"{case_id}.review.json"
    if private_path.is_file():
        data = json.loads(private_path.read_text())
        return ReviewerMetadata(
            important_constraints=list(data.get("important_constraints", [])),
            review_notes=data.get("review_notes"),
        )
    public_path = Path(cases_dir) / f"{case_id}.json"
    if public_path.is_file():
        data = json.loads(public_path.read_text())
        if "important_constraints" in data or "review_notes" in data:
            return ReviewerMetadata(
                important_constraints=list(data.get("important_constraints", [])),
                review_notes=data.get("review_notes"),
            )
    return None
